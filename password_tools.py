"""Готовый вспомогательный модуль для учебной регистрации.
Не хранит пароль открытым текстом. Изучение криптографии не является целью урока.
"""
import hashlib
import hmac
import secrets


def создать_хеш(пароль):
    # Случайная соль делает сохранённые значения разными даже для одинаковых паролей.
    соль = secrets.token_hex(16)
    хеш = hashlib.pbkdf2_hmac(
        "sha256", пароль.encode("utf-8"), bytes.fromhex(соль), 600000
    ).hex()
    # Соль не секретна. Сохраняем её вместе с хешем в одном текстовом поле.
    return соль + ":" + хеш


def проверить_пароль(пароль, сохранённое_значение):
    try:
        соль, ожидаемый_хеш = сохранённое_значение.split(":")
        if len(соль) != 32 or len(ожидаемый_хеш) != 64:
            return False
        вычисленный_хеш = hashlib.pbkdf2_hmac(
            "sha256", пароль.encode("utf-8"), bytes.fromhex(соль), 600000
        ).hex()
        return hmac.compare_digest(вычисленный_хеш, ожидаемый_хеш)
    except (ValueError, TypeError):
        return False
